PROMPTS = {"news": NEWS, "ideas": IDEAS}
EXTRA_FIELDS = {"news": (), "ideas": ("who_pays", "difficulty", "kz")}  # сохраняются в articles.extra


def _get_client() -> AsyncOpenAI:
    global _client
    if _client is None:
        _client = AsyncOpenAI(api_key=config.LLM_API_KEY, base_url=config.LLM_BASE_URL)
    return _client


async def classify(digest: str, articles: list[dict], events: list[dict], interests: str, excludes: str
                   ) -> list[dict] | None:
    """articles: [{id, source, title, text}], events: [{id, event}]. Возвращает список оценок по статьям,
    None — если ответ не разобрался (обычно обрезан): тогда пачку стоит разделить и повторить."""
    events_text = "\n".join(f"C{e['id']}: {e['event']}" for e in events) or "(нет)"
    articles_text = "\n\n".join(
        f"id={a['id']} | источник: {a['source']}\nЗаголовок: {a['title']}\nТекст: {a['text'] or '(только заголовок)'}"
        for a in articles)
    user = f"НЕДАВНИЕ СОБЫТИЯ:\n{events_text}\n\nНОВЫЕ СТАТЬИ:\n{articles_text}"
    resp = await _get_client().chat.completions.create(
        model=config.LLM_MODEL,
        messages=[{"role": "system", "content": PROMPTS[digest].format(interests=interests, excludes=excludes or "нет")},
                  {"role": "user", "content": user}],
        response_format={"type": "json_object"},
        max_tokens=8000,
        temperature=0.2,
    )
    content = resp.choices[0].message.content or "{}"
    try:
        return json.loads(content).get("items", [])
    except ValueError:
        log.warning("LLM вернула не JSON (%s, finish=%s): …%s", len(content), resp.choices[0].finish_reason,
                    content[-200:])
        return None
